$accountingPermissionNames = static function (callable $allows) use ($accountingPermissionCatalog): array {
    return $accountingPermissionCatalog
        ->flatMap(
            static fn (array $actions, string $group): array => array_map(
                static fn (PermissionAction $action): string => "admin.{$group}.{$action->value}",
                array_values(array_filter(
                    $actions,
                    static fn (PermissionAction $action): bool => $allows($group, $action),
                )),
            ),
        )
        ->values()
        ->all();
};

